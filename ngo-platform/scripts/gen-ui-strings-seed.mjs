// Generates supabase/seeds/ui_strings.sql from src/lib/i18n/defaults/*.json,
// so the DB seed and the code fallback never drift. Run: pnpm seed:ui-strings
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "src/lib/i18n/defaults";
const out = "supabase/seeds/ui_strings.sql";

const locales = readdirSync(dir)
  .filter((f) => /^[a-z]{2,3}(-[A-Z]{2})?\.json$/.test(f))
  .map((f) => f.replace(/\.json$/, ""))
  .sort();

const byKey = new Map();
for (const code of locales) {
  const messages = JSON.parse(readFileSync(join(dir, `${code}.json`), "utf8"));
  for (const [key, value] of Object.entries(messages)) {
    if (!byKey.has(key)) byKey.set(key, {});
    byKey.get(key)[code] = value;
  }
}

const q = (s) => `'${s.replaceAll("'", "''")}'`;
const rows = [...byKey.keys()]
  .sort()
  .map((key) => `  (${q(key)}, ${q(JSON.stringify(byKey.get(key)))})`);

writeFileSync(
  out,
  `-- GENERATED by scripts/gen-ui-strings-seed.mjs from ${dir}/*.json. Do not edit.
insert into public.ui_strings (key, value) values
${rows.join(",\n")}
on conflict (key) do update set value = excluded.value;
`,
);
console.log(`Wrote ${rows.length} keys (${locales.join(", ")}) to ${out}`);
